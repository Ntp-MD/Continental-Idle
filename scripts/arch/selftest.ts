/**
 * selftest.ts - the failure library run as a test.
 *
 * A validator that cannot catch a known-bad plan is not a validator; one that fires on a
 * known-good plan is noise. This drives every fixture through the real pipeline - migrate, the
 * host engine, the world model, the checks - and asserts:
 *   bad  fixtures produce the findings they are documented to produce
 *   good fixtures produce none of the findings they are documented to be free of
 * It also renders each fixture and regenerates architecture-skill/failure-library.md from the
 * measured results, so the documentation cannot drift away from the executable examples.
 */
